// Adapted from Lotus src/lib/emoji/catalog.ts. Unicode characters use the system emoji font.
function parse(lines) {
  return lines.map((line) => {
    const gap = line.indexOf(" ");
    const rest = line.slice(gap + 1);
    const bar = rest.indexOf("|");
    return {
      char: line.slice(0, gap),
      name: bar === -1 ? rest : rest.slice(0, bar),
      keywords: bar === -1 ? [] : rest.slice(bar + 1).split(" ").filter(Boolean)
    };
  });
}
